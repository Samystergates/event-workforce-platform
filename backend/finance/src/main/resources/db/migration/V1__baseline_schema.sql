CREATE TABLE IF NOT EXISTS invoices (
  id BIGINT NOT NULL AUTO_INCREMENT,
  invoice_number VARCHAR(255) NOT NULL,
  invoice_date DATE NOT NULL,
  invoice_type VARCHAR(50) NOT NULL,
  supplier_name VARCHAR(255) NOT NULL,
  supplier_address VARCHAR(255) NULL,
  supplier_postal_code VARCHAR(255) NULL,
  supplier_city VARCHAR(255) NULL,
  supplier_country VARCHAR(255) NULL,
  supplier_vat_number VARCHAR(255) NULL,
  supplier_kvk_number VARCHAR(255) NULL,
  customer_name VARCHAR(255) NULL,
  customer_address VARCHAR(255) NULL,
  customer_postal_code VARCHAR(255) NULL,
  customer_city VARCHAR(255) NULL,
  customer_country VARCHAR(255) NULL,
  customer_vat_number VARCHAR(255) NULL,
  customer_reference VARCHAR(255) NULL,
  amount_excl_vat DECIMAL(18,2) NULL,
  vat_amount DECIMAL(18,2) NULL,
  amount_incl_vat DECIMAL(18,2) NULL,
  currency VARCHAR(20) NULL,
  vat_percentage DECIMAL(18,4) NULL,
  vat_reverse_charge BIT(1) NULL,
  vat_specification LONGTEXT NULL,
  supplier_iban VARCHAR(255) NULL,
  supplier_bic VARCHAR(255) NULL,
  payment_terms VARCHAR(255) NULL,
  due_date DATE NULL,
  payment_reference VARCHAR(255) NULL,
  pdf_file_path VARCHAR(1024) NOT NULL,
  pdf_file_hash VARCHAR(255) NOT NULL,
  pdf_text_content LONGTEXT NULL,
  email_message_id VARCHAR(255) NULL,
  email_folder VARCHAR(255) NULL,
  email_sender VARCHAR(255) NULL,
  original_filename VARCHAR(255) NULL,
  extraction_confidence DOUBLE NULL,
  extraction_method VARCHAR(255) NULL,
  type_detection_method VARCHAR(255) NULL,
  extraction_warnings LONGTEXT NULL,
  validation_errors LONGTEXT NULL,
  missing_required_fields LONGTEXT NULL,
  is_valid BIT(1) NULL,
  is_matched BIT(1) NULL,
  is_paid BIT(1) NULL,
  imported_at DATETIME(6) NULL,
  created_at DATETIME(6) NULL,
  updated_at DATETIME(6) NULL,
  description_summary LONGTEXT NULL,
  service_period_start DATE NULL,
  service_period_end DATE NULL,
  purchase_order_number VARCHAR(255) NULL,
  project_reference VARCHAR(255) NULL,
  PRIMARY KEY (id),
  KEY idx_invoices_invoice_number (invoice_number),
  KEY idx_invoices_supplier_name (supplier_name),
  KEY idx_invoices_due_date (due_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS invoice_lines (
  id BIGINT NOT NULL AUTO_INCREMENT,
  description LONGTEXT NULL,
  quantity DECIMAL(18,3) NULL,
  unit_price DECIMAL(18,4) NULL,
  vat_percentage DECIMAL(18,4) NULL,
  amount_excl_vat DECIMAL(18,2) NULL,
  vat_amount DECIMAL(18,2) NULL,
  amount_incl_vat DECIMAL(18,2) NULL,
  invoice_id BIGINT NULL,
  PRIMARY KEY (id),
  KEY idx_invoice_lines_invoice_id (invoice_id),
  CONSTRAINT fk_invoice_lines_invoice FOREIGN KEY (invoice_id) REFERENCES invoices (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS transactions (
  id BIGINT NOT NULL AUTO_INCREMENT,
  transaction_id VARCHAR(255) NOT NULL,
  booking_date DATE NOT NULL,
  value_date DATE NULL,
  amount DECIMAL(18,2) NOT NULL,
  currency VARCHAR(20) NULL,
  debtor_name VARCHAR(255) NULL,
  debtor_iban VARCHAR(255) NULL,
  creditor_name VARCHAR(255) NULL,
  creditor_iban VARCHAR(255) NULL,
  description LONGTEXT NULL,
  remittance_info LONGTEXT NULL,
  end_to_end_id VARCHAR(255) NULL,
  mandate_id VARCHAR(255) NULL,
  camt_file_name VARCHAR(255) NULL,
  imported_at DATETIME(6) NULL,
  is_matched BIT(1) NULL,
  match_confidence DOUBLE NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_transactions_transaction_id (transaction_id),
  KEY idx_transactions_booking_date (booking_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS matches (
  id BIGINT NOT NULL AUTO_INCREMENT,
  transaction_id BIGINT NOT NULL,
  invoice_id BIGINT NOT NULL,
  match_status VARCHAR(50) NOT NULL,
  match_type VARCHAR(50) NOT NULL,
  confidence_score DOUBLE NOT NULL,
  matched_on_amount BIT(1) NULL,
  matched_on_iban BIT(1) NULL,
  matched_on_reference BIT(1) NULL,
  matched_on_date_range BIT(1) NULL,
  matched_amount DECIMAL(18,2) NULL,
  is_partial_payment BIT(1) NULL,
  payment_group_id VARCHAR(255) NULL,
  confirmed_by_user VARCHAR(255) NULL,
  confirmed_at DATETIME(6) NULL,
  notes LONGTEXT NULL,
  created_at DATETIME(6) NULL,
  updated_at DATETIME(6) NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_invoice_transaction (invoice_id, transaction_id),
  KEY idx_matches_transaction (transaction_id),
  CONSTRAINT fk_matches_invoice FOREIGN KEY (invoice_id) REFERENCES invoices (id),
  CONSTRAINT fk_matches_transaction FOREIGN KEY (transaction_id) REFERENCES transactions (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
